#!/usr/bin/env bash
set -euo pipefail

MODEL_ID=Qwen/Qwen3.8-27B
REPO_CACHE_NAME=models--Qwen--Qwen3.8-27B
SCRIPT_DIR=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)

die() {
    printf 'ERROR: %s\n' "$*" >&2
    exit 1
}

note() {
    printf '%s\n' "$*"
}

usage() {
    cat <<'EOF'
Usage: bash coding-agent/vllm/setup.sh [MODEL_OR_CACHE_DIRECTORY] [GPU_COUNT]

MODEL_OR_CACHE_DIRECTORY may be:
  - the model snapshot/local directory containing config.json; or
  - an HF_HOME directory containing hub/; or
  - an HF_HUB_CACHE directory containing models--Qwen--Qwen3.8-27B.

If omitted, HF_HUB_CACHE, HF_HOME, and ~/.cache/huggingface are checked.
VLLM_BIN may name an approved vLLM executable that is not on PATH.
EOF
}

absolute_dir() {
    [ -d "$1" ] || return 1
    (cd -- "$1" && pwd -P)
}

snapshot_from_hub() {
    local hub=$1 repo revision snapshot count candidate
    repo="$hub/$REPO_CACHE_NAME"
    [ -d "$repo/snapshots" ] || return 1

    if [ -s "$repo/refs/main" ]; then
        IFS= read -r revision < "$repo/refs/main"
        snapshot="$repo/snapshots/$revision"
        [ -d "$snapshot" ] && absolute_dir "$snapshot" && return 0
    fi

    count=0
    snapshot=
    while IFS= read -r candidate; do
        snapshot=$candidate
        count=$((count + 1))
    done < <(find "$repo/snapshots" -mindepth 1 -maxdepth 1 -type d -print)

    [ "$count" -eq 1 ] || return 1
    absolute_dir "$snapshot"
}

resolve_model_dir() {
    local candidate=$1 resolved

    if [ -f "$candidate/config.json" ]; then
        absolute_dir "$candidate"
        return
    fi
    if resolved=$(snapshot_from_hub "$candidate" 2>/dev/null); then
        printf '%s\n' "$resolved"
        return
    fi
    if resolved=$(snapshot_from_hub "$candidate/hub" 2>/dev/null); then
        printf '%s\n' "$resolved"
        return
    fi
    return 1
}

find_default_model() {
    local candidate resolved
    if [ -n "${HF_HUB_CACHE:-}" ]; then
        candidate=$HF_HUB_CACHE
        if resolved=$(resolve_model_dir "$candidate" 2>/dev/null); then
            printf '%s\n' "$resolved"
            return
        fi
    fi
    if [ -n "${HF_HOME:-}" ]; then
        candidate=$HF_HOME
        if resolved=$(resolve_model_dir "$candidate" 2>/dev/null); then
            printf '%s\n' "$resolved"
            return
        fi
    fi
    resolve_model_dir "$HOME/.cache/huggingface"
}

resolve_executable() {
    local requested=$1 resolved
    if [[ "$requested" == */* ]]; then
        [ -x "$requested" ] || return 1
        resolved=$(cd -- "$(dirname -- "$requested")" && pwd -P)/$(basename -- "$requested")
    else
        resolved=$(command -v "$requested") || return 1
    fi
    printf '%s\n' "$resolved"
}

write_env() {
    local target=$1 model_dir=$2 tp_size=$3 vllm_bin=$4
    {
        printf '# Generated by coding-agent/vllm/setup.sh. Safe to edit.\n'
        printf 'export CARINA_VLLM_BIN=%q\n' "$vllm_bin"
        printf 'export CARINA_MODEL_DIR=%q\n' "$model_dir"
        printf 'export CARINA_MODEL_NAME=%q\n' "$MODEL_ID"
        printf 'export CARINA_TP_SIZE=%q\n' "$tp_size"
        printf 'export CARINA_MAX_MODEL_LEN=%q\n' 32768
        printf 'export CARINA_VLLM_HOST=%q\n' 127.0.0.1
        printf 'export CARINA_VLLM_PORT=%q\n' 8000
    } > "$target"
}

if [ "${1:-}" = -h ] || [ "${1:-}" = --help ]; then
    usage
    exit 0
fi
[ "$#" -le 2 ] || {
    usage >&2
    die "too many arguments"
}
[ "$(uname -s)" = Linux ] || die "run this setup on Carina Linux, not on CPI or the personal PC"

input=${1:-}
tp_size=${2:-${CARINA_TP_SIZE:-1}}
case "$tp_size" in
    ''|*[!0-9]*|0) die "GPU_COUNT must be a positive integer" ;;
esac

if [ -n "$input" ]; then
    model_dir=$(resolve_model_dir "$input" 2>/dev/null) || {
        usage >&2
        die "could not find $MODEL_ID beneath '$input'"
    }
else
    model_dir=$(find_default_model 2>/dev/null) || {
        usage >&2
        die "model not found; pass its local directory or Hugging Face cache directory"
    }
fi

[ -r "$model_dir/config.json" ] || die "missing readable config.json in $model_dir"
if ! find -L "$model_dir" -maxdepth 1 -type f \
    \( -name '*.safetensors' -o -name '*.safetensors.index.json' \) \
    -print -quit | grep -q .; then
    die "no readable safetensors weights found in $model_dir (the cache may contain broken symlinks)"
fi

vllm_bin=$(resolve_executable "${VLLM_BIN:-vllm}") || \
    die "vllm is unavailable; load an approved Carina vLLM environment, then rerun this phase"
vllm_version=$("$vllm_bin" --version 2>/dev/null || printf 'unknown')
note "Checking vLLM $vllm_version for Qwen3.8 parser support..."
vllm_help=$("$vllm_bin" serve --help 2>&1 || true)
grep -q 'qwen3_coder' <<< "$vllm_help" || \
    die "vLLM $vllm_version is too old: its serve command does not provide the qwen3_coder parser"

config_dir="$HOME/.config/carina-coding"
bin_dir="$HOME/.local/bin"
mkdir -p "$config_dir" "$bin_dir"
write_env "$config_dir/vllm.env" "$model_dir" "$tp_size" "$vllm_bin"
install -m 0755 "$SCRIPT_DIR/start-vllm.sh" "$bin_dir/carina-vllm"

note "vLLM/Qwen setup complete."
note "Model: $model_dir"
note "vLLM: $vllm_bin ($vllm_version)"
note "Tensor-parallel GPUs: $tp_size"
note "Next: bash coding-agent/codex/setup.sh"


#!/usr/bin/env bash
set -euo pipefail

SCRIPT_DIR=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)

die() {
    printf 'ERROR: %s\n' "$*" >&2
    exit 1
}

note() {
    printf '%s\n' "$*"
}

resolve_executable() {
    local requested=$1 resolved
    if [[ "$requested" == */* ]]; then
        [ -x "$requested" ] || return 1
        resolved=$(cd -- "$(dirname -- "$requested")" && pwd -P)/$(basename -- "$requested")
    else
        resolved=$(command -v "$requested") || return 1
    fi
    printf '%s\n' "$resolved"
}

write_client_env() {
    local target=$1 codex_bin=$2 codex_home=$3
    {
        printf '# Generated by coding-agent/codex/setup.sh. Safe to edit.\n'
        printf 'export CARINA_CODEX_BIN=%q\n' "$codex_bin"
        printf 'export CARINA_CODEX_HOME=%q\n' "$codex_home"
    } > "$target"
}

write_codex_config() {
    local target=$1
    cat > "$target" <<'EOF'
model = "Qwen/Qwen3.8-27B"
model_provider = "vllm"
model_context_window = 32768
approval_policy = "on-request"
sandbox_mode = "workspace-write"
web_search = "disabled"

[model_providers.vllm]
name = "Carina local Qwen vLLM"
base_url = "http://127.0.0.1:8000/v1"
wire_api = "responses"
requires_openai_auth = false
EOF
}

if [ "${1:-}" = -h ] || [ "${1:-}" = --help ]; then
    printf '%s\n' 'Usage: bash coding-agent/codex/setup.sh'
    printf '%s\n' 'Set CODEX_BIN if the approved Codex executable is not on PATH.'
    exit 0
fi
[ "$#" -eq 0 ] || die "this setup takes no positional arguments"
[ "$(uname -s)" = Linux ] || die "run this setup on Carina Linux, not on CPI or the personal PC"

config_dir="$HOME/.config/carina-coding"
vllm_env="$config_dir/vllm.env"
[ -r "$vllm_env" ] || \
    die "vLLM setup is incomplete; run bash coding-agent/vllm/setup.sh first"

codex_bin=$(resolve_executable "${CODEX_BIN:-codex}") || \
    die "codex is unavailable; install/load the approved Carina Codex CLI, then rerun this phase"
codex_version=$("$codex_bin" --version 2>/dev/null || printf 'unknown')

codex_home="$HOME/.local/share/carina-coding/codex"
bin_dir="$HOME/.local/bin"
mkdir -p "$config_dir" "$codex_home" "$bin_dir"
write_client_env "$config_dir/codex.env" "$codex_bin" "$codex_home"
write_codex_config "$codex_home/config.toml"
install -m 0755 "$SCRIPT_DIR/start.sh" "$bin_dir/carina-codex"
install -m 0755 "$SCRIPT_DIR/session.sh" "$bin_dir/carina-code"

note "Codex client setup complete."
note "Codex: $codex_bin ($codex_version)"
note "Codex configuration: $codex_home/config.toml"
note "Inside each GPU allocation, run: carina-code"

